use bsc_rust_tests::alignment::{remaining_inventory, RemainingTestScript};
use bsc_rust_tests::locate_project_root;
use std::collections::BTreeMap;
use std::fs;
use std::process::ExitCode;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("remaining inventory FAILED:\n{error}");
            ExitCode::from(1)
        }
    }
}

fn run() -> Result<(), String> {
    let mode = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "--check".to_owned());
    if std::env::args().nth(2).is_some() || !matches!(mode.as_str(), "--check" | "--write") {
        return Err("usage: remaining [--check|--write]".to_owned());
    }

    let entries = remaining_inventory()?;
    let rendered = render_inventory(&entries);
    let path = locate_project_root()?.join("rust-tests/REMAINING.md");
    match mode.as_str() {
        "--write" => {
            fs::write(&path, rendered.as_bytes())
                .map_err(|error| format!("write {}: {error}", path.display()))?;
            println!(
                "updated {} with {} remaining test scripts",
                path.display(),
                entries.len()
            );
        }
        "--check" => {
            let actual = fs::read_to_string(&path)
                .map_err(|error| format!("read {}: {error}", path.display()))?;
            if actual != rendered {
                return Err(format!(
                    "{} is stale; run `pixi run just inventory-update`",
                    path.display()
                ));
            }
            println!(
                "remaining inventory ok: {} scripts, {} statically declared contracts",
                entries.len(),
                entries
                    .iter()
                    .map(|entry| entry.statically_declared_contracts)
                    .sum::<usize>()
            );
        }
        _ => unreachable!(),
    }
    Ok(())
}

fn render_inventory(entries: &[RemainingTestScript]) -> String {
    let static_contracts = entries
        .iter()
        .map(|entry| entry.statically_declared_contracts)
        .sum::<usize>();
    let dynamic_only = entries
        .iter()
        .filter(|entry| entry.statically_declared_contracts == 0)
        .count();
    let mut suites = BTreeMap::<&str, (usize, usize, usize)>::new();
    for entry in entries {
        let suite = entry
            .origin
            .strip_prefix("testsuite/")
            .and_then(|path| path.split('/').next())
            .unwrap_or("unknown");
        let summary = suites.entry(suite).or_default();
        summary.0 += 1;
        summary.1 += entry.statically_declared_contracts;
        if entry.statically_declared_contracts == 0 {
            summary.2 += 1;
        }
    }

    let mut output = String::new();
    output.push_str("# Remaining testsuite inventory\n\n");
    output.push_str("> Generated by `pixi run just inventory-update`; do not edit manually.\n");
    output.push_str(
        "> `inventory-check` uses the same parser and migration registry as `test-alignment`.\n\n",
    );
    output.push_str("## Summary\n\n");
    output.push_str(&format!(
        "- Remaining test scripts: **{}**\n",
        entries.len()
    ));
    output.push_str(&format!(
        "- Remaining statically declared contracts: **{static_contracts}**\n"
    ));
    output.push_str(&format!(
        "- Scripts with one or more statically recognized contracts: **{}**\n",
        entries.len() - dynamic_only
    ));
    output.push_str(&format!(
        "- Scripts requiring fully dynamic or custom Tcl analysis: **{dynamic_only}**\n\n"
    ));
    output.push_str("A nonzero static count is an inventory fact, not an automatic migration approval. Scripts may still contain additional assertions, dynamic Tcl, custom helpers, generated artifacts, XFAIL rules, or unsupported link/simulation flows. Curated safe candidates and blockers are tracked in [`NEXT.md`](NEXT.md).\n\n");

    output.push_str("## By testsuite area\n\n");
    output.push_str(
        "| Area | Remaining scripts | Static contracts | Dynamic/custom-only scripts |\n",
    );
    output.push_str("| --- | ---: | ---: | ---: |\n");
    for (suite, (scripts, contracts, dynamic)) in suites {
        output.push_str(&format!(
            "| `{suite}` | {scripts} | {contracts} | {dynamic} |\n"
        ));
    }

    output.push_str("\n## Complete remaining list\n\n");
    output.push_str("| Origin | Static contracts | Initial classification |\n");
    output.push_str("| --- | ---: | --- |\n");
    for entry in entries {
        let classification = if entry.statically_declared_contracts == 0 {
            "Dynamic/custom Tcl analysis required"
        } else {
            "Static contracts present; review remaining Tcl"
        };
        output.push_str(&format!(
            "| `{}` | {} | {} |\n",
            entry.origin, entry.statically_declared_contracts, classification
        ));
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_deterministic_summary_and_rows() {
        let entries = [
            RemainingTestScript {
                origin: "testsuite/bsc.alpha/one.exp".to_owned(),
                statically_declared_contracts: 2,
            },
            RemainingTestScript {
                origin: "testsuite/bsc.beta/two.exp".to_owned(),
                statically_declared_contracts: 0,
            },
        ];
        let rendered = render_inventory(&entries);
        assert!(rendered.contains("Remaining test scripts: **2**"));
        assert!(rendered.contains("Remaining statically declared contracts: **2**"));
        assert!(rendered.contains("| `bsc.alpha` | 1 | 2 | 0 |"));
        assert!(rendered.contains("Dynamic/custom Tcl analysis required"));
    }
}
